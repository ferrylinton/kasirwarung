// Initial language from localStorage, defaults to 'id' (Bahasa Indonesia) as requested!
const savedLanguage = typeof window !== 'undefined'
  ? localStorage.getItem('kasirwarung_language') || 'id'
  : 'id';

i18n
  .use(initReactI18next)
  .init({
    resources: {
      id: { translation: idTranslations },
      en: { translation: enTranslations },
    },
    lng: savedLanguage,
    fallbackLng: 'id', // Default language: Indonesia
    interpolation: {
      escapeValue: false,
    },
  });

// Set document html lang attribute
if (typeof document !== 'undefined') {
  document.documentElement.lang = savedLanguage;
}

// Ensure html lang attribute is synchronized on any i18n language change
i18n.on('languageChanged', (lng) => {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lng.startsWith('en') ? 'en' : 'id';
  }
});

export function setAppLanguage(lang: 'id' | 'en') {
  i18n.changeLanguage(lang);
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('kasirwarung_language', lang);
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
  }
}

export default i18n;
